export const dashboardText = (
  currentLocale: Locale,
  key: string,
  values: Record<string, string | number> = {}
) => {
  const template = dashboardCopy[currentLocale][key] ?? dashboardCopy.en[key] ?? key;
  return Object.entries(values).reduce(
    (text, [name, value]) => text.replaceAll(`{${name}}`, String(value)),
    template
  );
};

export const dashboardIntlLocale = (currentLocale: Locale) => (currentLocale === 'ms' ? 'ms-MY' : 'en-US');
